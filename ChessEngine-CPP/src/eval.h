// -------------------------------------------------------------------------
// Fast Evaluation Function
// -------------------------------------------------------------------------
inline int evaluate(const Board& board) {
    Score score = 0;
    int gamePhase = 0;

    for (int p = 0; p < 6; ++p) {
        // White pieces: direct addition
        uint64_t wPieces = board.pieces[WHITE][p];
        while (wPieces) {
            int sq = std::countr_zero(wPieces);
            score += PIECE_TABLES[p][sq];
            gamePhase += PHASE_WEIGHTS[p];
            wPieces &= wPieces - 1;
        }

        // Black pieces: direct subtraction, mirrored square (sq ^ 56)
        uint64_t bPieces = board.pieces[BLACK][p];
        while (bPieces) {
            int sq = std::countr_zero(bPieces);
            score -= PIECE_TABLES[p][sq ^ 56];
            gamePhase += PHASE_WEIGHTS[p];
            bPieces &= bPieces - 1;
        }
    }

    // Phase interpolation
    int mgPhase = std::min(gamePhase, TOTAL_PHASE);
    int egPhase = TOTAL_PHASE - mgPhase;

    int eval = (mg_score(score) * mgPhase + eg_score(score) * egPhase) / TOTAL_PHASE;

    // Return perspective score (positive means side-to-move is winning)
    return (board.turn == WHITE) ? eval : -eval;
}