// -------------------------------------------------------------------------
// Score Type & Packing Helpers
// -------------------------------------------------------------------------
// Score is stored as: (mg << 16) + eg.
// Adding or subtracting two Scores calculates both phases simultaneously.
using Score = int32_t;

inline constexpr Score make_score(int16_t mg, int16_t eg) {
    return (static_cast<Score>(static_cast<uint16_t>(mg)) << 16) | 
            static_cast<uint16_t>(eg);
}

inline constexpr int16_t mg_score(Score s) {
    return static_cast<int16_t>(static_cast<uint32_t>(s) >> 16);
}

inline constexpr int16_t eg_score(Score s) {
    return static_cast<int16_t>(s & 0xFFFF);
}

